/**
 * Maps Search Console queries to the course/section page that should rank for
 * them and lists striking-distance targets (position 8-20, 150+ impressions).
 *   node scripts/seo-query-map.mjs <courses.json> > docs/data/search-console/query-map.md
 * courses.json: [{ link, code, title, status, section: { link } }] from the DB.
 */
import fs from "node:fs";

const courses = JSON.parse(fs.readFileSync(process.argv[2], "utf8")).filter((c) => c.status === "PUBLISHED");
const dir = "docs/data/search-console/last-16-months";
const rows = (f) =>
  fs.readFileSync(`${dir}/${f}`, "utf8").trim().split("\n").slice(1).flatMap((l) => {
    const m = l.match(/^(.*),(\d+),(\d+),([\d.]+)%,([\d.]+)$/);
    if (!m) return []; // a few queries contain line breaks
    return [ { key: m[1].replace(/^"|"$/g, ""), clicks: +m[2], imp: +m[3], pos: +m[5] }];
  });

const LEVEL = { "cert 4": "iv", "cert iv": "iv", "certificate 4": "iv", "cert 3": "iii", "cert iii": "iii", "certificate 3": "iii", "cert 2": "ii", "diploma": "diploma" };
const STOP = new Set(["fast","track","rpl","course","courses","online","certificate","cert","in","of","and","the","for","a","to","how","what","is","australia","qualification","licence","license","become","start","your","career","tech","technology","iii","iv","ii","diploma","3","4","2","5","with"]);
const words = (s) => s.toLowerCase().replace(/&/g, " ").replace(/[^a-z0-9 ]/g, " ").split(/\s+/).filter((w) => w && !STOP.has(w));
const levelOf = (s) => { s = s.toLowerCase(); for (const [k, v] of Object.entries(LEVEL)) if (s.includes(k)) return v; const m = s.match(/certificate (iii|iv|ii)\b/); return m ? m[1] : s.includes("diploma") ? "diploma" : null; };
const SYN = { electrician: "electrotechnology", electrical: "electrotechnology", hvac: "refrigeration", "air con": "refrigeration", childcare: "early childhood", "aged care": "individual support ageing", chef: "cookery", cooking: "cookery", tae: "training assessment", whs: "work health safety", mechanic: "mechanical", builder: "building construction", diesel: "diesel", tiler: "tiling" };

const idx = courses.map((c) => ({ c, w: new Set(words(c.title)), lvl: levelOf(c.title) }));
function match(q) {
  const code = q.match(/\b[a-z]{3}\d{5}\b/i);
  if (code) { const hit = courses.find((c) => (c.code || "").toLowerCase() === code[0].toLowerCase()); if (hit) return hit; }
  let qq = q.toLowerCase();
  for (const [k, v] of Object.entries(SYN)) if (qq.includes(k)) qq += " " + v;
  const qw = new Set(words(qq)); if (!qw.size) return null;
  const ql = levelOf(q);
  let best = null, bs = 0;
  for (const { c, w, lvl } of idx) {
    let s = 0; for (const x of qw) if (w.has(x)) s += 1;
    if (!s) continue;
    s = s / Math.max(qw.size, 1) + (ql && lvl === ql ? 0.5 : ql && lvl && lvl !== ql ? -0.4 : 0) + s * 0.05;
    if (s > bs) { bs = s; best = c; }
  }
  return bs >= 0.6 ? best : null;
}

const queries = rows("Queries.csv");
const pages = rows("Pages.csv");
const BRAND = /^(rpl fast ?track|rplfasttrack|rpl fastrack)\b/;
const map = new Map();
const unmapped = [];
for (const q of queries) {
  if (BRAND.test(q.key)) continue;
  const c = match(q.key);
  if (!c) { if (q.imp >= 100) unmapped.push(q); continue; }
  if (!map.has(c.link)) map.set(c.link, { c, qs: [], imp: 0, clicks: 0 });
  const e = map.get(c.link); e.qs.push(q); e.imp += q.imp; e.clicks += q.clicks;
}

let out = `# Search Console: query → page map\n\nGenerated by \`scripts/seo-query-map.mjs\` from \`last-16-months/Queries.csv\` (${queries.length} queries). Each non-brand query is matched to the course page that should rank for it (by qualification code, level and topic words). The Search Console export has no per-page queries except for two pages, so this is a keyword match, not observed data: check the target in the Search Console URL inspection before acting on a weak match.\n\n`;
out += `## Striking distance (position 8–20, 150+ impressions)\n\nThe cheapest wins: already on page 1–2, so content, title and internal links can push them up.\n\n| Query | Impr. | Clicks | Pos. | Target page |\n|---|---:|---:|---:|---|\n`;
const sd = [...map.values()].flatMap((e) => e.qs.map((q) => ({ ...q, c: e.c }))).filter((q) => q.pos >= 8 && q.pos <= 20 && q.imp >= 150).sort((a, b) => b.imp - a.imp);
for (const q of sd.slice(0, 40)) out += `| ${q.key} | ${q.imp} | ${q.clicks} | ${q.pos} | /courses/${q.c.link} |\n`;
out += `\n## Page 3+ with huge impressions (position > 20, 1,000+ impressions)\n\nThese need real content and links, not just a title.\n\n| Query | Impr. | Pos. | Target page |\n|---|---:|---:|---|\n`;
for (const q of [...map.values()].flatMap((e) => e.qs.map((x) => ({ ...x, c: e.c }))).filter((q) => q.pos > 20 && q.imp >= 1000).sort((a, b) => b.imp - a.imp).slice(0, 25)) out += `| ${q.key} | ${q.imp} | ${q.pos} | /courses/${q.c.link} |\n`;
out += `\n## Queries per target page (top 25 pages by impressions)\n`;
for (const e of [...map.values()].sort((a, b) => b.imp - a.imp).slice(0, 25)) {
  out += `\n### /courses/${e.c.link}\n${e.c.code} · ${e.imp} impressions · ${e.clicks} clicks over ${e.qs.length} queries\n\n`;
  for (const q of e.qs.sort((a, b) => b.imp - a.imp).slice(0, 6)) out += `- ${q.key} (${q.imp} impr, pos ${q.pos})\n`;
}
out += `\n## Unmatched queries with 100+ impressions (need a page or a guide)\n\n`;
for (const q of unmapped.sort((a, b) => b.imp - a.imp).slice(0, 40)) out += `- ${q.key} (${q.imp} impr, pos ${q.pos})\n`;
out += `\n## Old URLs in Search Console that now redirect\n\n`;
const live = new Set(courses.map((c) => c.link));
for (const p of pages) { const m = p.key.match(/\/courses\/(.+)$/); if (m && !live.has(m[1])) out += `- ${m[1]} (${p.clicks} clicks, ${p.imp} impr): redirected (Redirect table or LEGACY_REDIRECTS)\n`; }
console.log(out);
